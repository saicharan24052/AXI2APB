module apb_addr_calc #(
    parameter AW = 32,
    parameter IW = 4,
    parameter LW = 4
)
(
    input                       PCLK,
    input                       PRESETn,
    input [AW+IW+LW+7:0]       waddr_ctrl_rdata,
    input                       waddr_ren,
    input                       waddr_fifo_empty,
    output                      waddr_fifo_pop,
    input [AW+IW+LW+7:0]       raddr_ctrl_rdata,
    input                       raddr_ren,
    input                       raddr_fifo_empty,
    output                      raddr_fifo_pop,
    output [AW+IW+LW+2:0]      r_write_prot_addr_id,
    output [AW+IW+LW+2:0]      r_read_prot_addr_id,
    output                      w_addr_fe,
    output                      r_addr_fe
);

localparam W_IDLE = 2'b00;
localparam W_WAIT = 2'b01;
localparam W_GEN  = 2'b10;

localparam R_IDLE = 2'b00;
localparam R_WAIT = 2'b01;
localparam R_GEN  = 2'b10;

reg [1:0] w_state;
reg [1:0] r_state;

/*
 * AXI address/control FIFO format:
 *
 * [AW+IW+LW+7 : AW+IW+LW+5] = PROT
 * [AW+IW+LW+4 : AW+IW+LW+3] = BURST
 * [AW+IW+LW+2 : AW+IW+LW  ] = SIZE
 * [AW+IW+LW-1 : AW+IW     ] = LEN
 * [AW+IW-1    : IW        ] = ADDR
 * [IW-1      : 0          ] = ID
 */
wire [AW-1:0] w_start_addr_in =
    waddr_ctrl_rdata[AW+IW-1:IW];
wire [IW-1:0] w_id_in =
    waddr_ctrl_rdata[IW-1:0];
wire [LW-1:0] w_len_in =
    waddr_ctrl_rdata[AW+IW+LW-1:AW+IW];
wire [2:0] w_size_in =
    waddr_ctrl_rdata[AW+IW+LW+2:AW+IW+LW];
wire [1:0] w_burst_in =
    waddr_ctrl_rdata[AW+IW+LW+4:AW+IW+LW+3];
wire [2:0] w_prot_in =
    waddr_ctrl_rdata[AW+IW+LW+7:AW+IW+LW+5];

wire [AW-1:0] r_start_addr_in =
    raddr_ctrl_rdata[AW+IW-1:IW];
wire [IW-1:0] r_id_in =
    raddr_ctrl_rdata[IW-1:0];
wire [LW-1:0] r_len_in =
    raddr_ctrl_rdata[AW+IW+LW-1:AW+IW];
wire [2:0] r_size_in =
    raddr_ctrl_rdata[AW+IW+LW+2:AW+IW+LW];
wire [1:0] r_burst_in =
    raddr_ctrl_rdata[AW+IW+LW+4:AW+IW+LW+3];
wire [2:0] r_prot_in =
    raddr_ctrl_rdata[AW+IW+LW+7:AW+IW+LW+5];

/* Local generated-address FIFO status. */
wire w_addr_ff;
wire r_addr_ff;

/* Payload written into the local generated-address FIFOs. */
wire [AW+IW+LW+2:0] w_calc_addr_ctrl;
wire [AW+IW+LW+2:0] r_calc_addr_ctrl;

/*
 * 2^AxSIZE bytes per AXI beat.
 * The expression is sized to AW bits so that all arithmetic remains
 * in the address width.
 */
wire [AW-1:0] w_beat_bytes_in =
    ({{(AW-1){1'b0}},1'b1} << w_size_in);
wire [AW-1:0] r_beat_bytes_in =
    ({{(AW-1){1'b0}},1'b1} << r_size_in);

/*
 * Legal AXI WRAP lengths are 2, 4, 8 and 16 beats, corresponding
 * to AWLEN = 1, 3, 7 and 15.
 */
function automatic [2:0] wrap_len_log2;
    input [LW-1:0] len;
    begin
        case (len)
            1:      wrap_len_log2 = 3'd1;
            3:      wrap_len_log2 = 3'd2;
            7:      wrap_len_log2 = 3'd3;
            15:     wrap_len_log2 = 3'd4;
            default: wrap_len_log2 = 3'd0;
        endcase
    end
endfunction

wire w_wrap_valid =
    (w_len_in == {{(LW-1){1'b0}},1'b1}) ||
    (w_len_in == {{(LW-2){1'b0}},2'b11}) ||
    (w_len_in == {{(LW-3){1'b0}},3'b111}) ||
    (w_len_in == {{(LW-4){1'b0}},4'b1111});

wire r_wrap_valid =
    (r_len_in == {{(LW-1){1'b0}},1'b1}) ||
    (r_len_in == {{(LW-2){1'b0}},2'b11}) ||
    (r_len_in == {{(LW-3){1'b0}},3'b111}) ||
    (r_len_in == {{(LW-4){1'b0}},4'b1111});

wire [AW-1:0] w_wrap_size_in =
    w_beat_bytes_in << wrap_len_log2(w_len_in);
wire [AW-1:0] r_wrap_size_in =
    r_beat_bytes_in << wrap_len_log2(r_len_in);

wire [AW-1:0] w_wrap_base_in =
    w_start_addr_in &
    ~(w_wrap_size_in - {{(AW-1){1'b0}},1'b1});
wire [AW-1:0] r_wrap_base_in =
    r_start_addr_in &
    ~(r_wrap_size_in - {{(AW-1){1'b0}},1'b1});

/* Active write burst. */
reg [LW:0]   w_count;
reg [AW-1:0] w_curr_addr;
reg [AW-1:0] w_beat_bytes;
reg [AW-1:0] w_wrap_size;
reg [AW-1:0] w_wrap_base;
reg [LW-1:0] w_len;
reg [1:0]    w_burst;
reg [IW-1:0] w_id;
reg [2:0]    w_prot;

/* Active read burst. */
reg [LW:0]   r_count;
reg [AW-1:0] r_curr_addr;
reg [AW-1:0] r_beat_bytes;
reg [AW-1:0] r_wrap_size;
reg [AW-1:0] r_wrap_base;
reg [LW-1:0] r_len;
reg [1:0]    r_burst;
reg [IW-1:0] r_id;
reg [2:0]    r_prot;

wire [AW-1:0] w_next_addr_incr =
    w_curr_addr + w_beat_bytes;
wire [AW-1:0] r_next_addr_incr =
    r_curr_addr + r_beat_bytes;

/*
 * AXI BURST encoding:
 *   2'b00 = FIXED
 *   2'b01 = INCR
 *   2'b10 = WRAP
 *   2'b11 = RESERVED
 *
 * Reserved traffic is treated as INCR for robustness; it is not
 * generated by a legal AXI master.
 */
wire [AW-1:0] w_next_addr =
    (w_burst == 2'b00) ? w_curr_addr :
    ((w_burst == 2'b10) && (w_wrap_size != {AW{1'b0}}) &&
     (w_next_addr_incr >= (w_wrap_base + w_wrap_size))) ?
        (w_wrap_base +
         (w_next_addr_incr - (w_wrap_base + w_wrap_size))) :
        w_next_addr_incr;

wire [AW-1:0] r_next_addr =
    (r_burst == 2'b00) ? r_curr_addr :
    ((r_burst == 2'b10) && (r_wrap_size != {AW{1'b0}}) &&
     (r_next_addr_incr >= (r_wrap_base + r_wrap_size))) ?
        (r_wrap_base +
         (r_next_addr_incr - (r_wrap_base + r_wrap_size))) :
        r_next_addr_incr;

/*
 * IMPORTANT:
 * The generated FIFO is the ONLY driver of the output ports
 * r_write_prot_addr_id and r_read_prot_addr_id.
 *
 * w_calc_addr_ctrl/r_calc_addr_ctrl are the FIFO write-data buses.
 * Leaving these buses undriven causes X data to be written into the
 * generated FIFO and can prevent the APB slave decoder from seeing a
 * valid address, which can look like an infinite wait in a testbench.
 */
assign w_calc_addr_ctrl = {w_prot, w_len, w_curr_addr, w_id};
assign r_calc_addr_ctrl = {r_prot, r_len, r_curr_addr, r_id};

assign waddr_fifo_pop =
    (w_state == W_IDLE) &&
    !waddr_fifo_empty &&
    !w_addr_ff;

assign raddr_fifo_pop =
    (r_state == R_IDLE) &&
    !raddr_fifo_empty &&
    !r_addr_ff;

wire w_addr_push =
    (w_state == W_GEN) && !w_addr_ff;

wire r_addr_push =
    (r_state == R_GEN) && !r_addr_ff;

always @(posedge PCLK or negedge PRESETn) begin
    if (!PRESETn) begin
        w_state      <= W_IDLE;
        w_count      <= '0;
        w_curr_addr  <= '0;
        w_beat_bytes <= '0;
        w_wrap_size  <= '0;
        w_wrap_base  <= '0;
        w_len        <= '0;
        w_burst      <= 2'b00;
        w_id         <= '0;
        w_prot       <= '0;
    end
    else begin
        case (w_state)
            W_IDLE: begin
                if (waddr_fifo_pop)
                    w_state <= W_WAIT;
            end

            W_WAIT: begin
                /*
                 * The source FIFO was popped on the previous edge.
                 * Its synchronous RAM output is now valid.
                 */
                w_curr_addr  <= w_start_addr_in;
                w_beat_bytes <= w_beat_bytes_in;
                w_wrap_size  <= w_wrap_valid ? w_wrap_size_in : '0;
                w_wrap_base  <= w_wrap_valid ? w_wrap_base_in : '0;
                w_len        <= w_len_in;
                w_burst      <= w_burst_in;
                w_id         <= w_id_in;
                w_prot       <= w_prot_in;
                w_count      <= '0;
                w_state      <= W_GEN;
            end

            W_GEN: begin
                /*
                 * One FIFO push represents exactly one APB transfer.
                 * For AWLEN=N, this executes N+1 pushes.
                 */
                if (w_addr_push) begin
                    if (w_count == {1'b0,w_len}) begin
                        w_count <= '0;
                        w_state <= W_IDLE;
                    end
                    else begin
                        w_count     <= w_count + 1'b1;
                        w_curr_addr <= w_next_addr;
                    end
                end
            end

            default: begin
                w_state <= W_IDLE;
            end
        endcase
    end
end

always @(posedge PCLK or negedge PRESETn) begin
    if (!PRESETn) begin
        r_state      <= R_IDLE;
        r_count      <= '0;
        r_curr_addr  <= '0;
        r_beat_bytes <= '0;
        r_wrap_size  <= '0;
        r_wrap_base  <= '0;
        r_len        <= '0;
        r_burst      <= 2'b00;
        r_id         <= '0;
        r_prot       <= '0;
    end
    else begin
        case (r_state)
            R_IDLE: begin
                if (raddr_fifo_pop)
                    r_state <= R_WAIT;
            end

            R_WAIT: begin
                r_curr_addr  <= r_start_addr_in;
                r_beat_bytes <= r_beat_bytes_in;
                r_wrap_size  <= r_wrap_valid ? r_wrap_size_in : '0;
                r_wrap_base  <= r_wrap_valid ? r_wrap_base_in : '0;
                r_len        <= r_len_in;
                r_burst      <= r_burst_in;
                r_id         <= r_id_in;
                r_prot       <= r_prot_in;
                r_count      <= '0;
                r_state      <= R_GEN;
            end

            R_GEN: begin
                if (r_addr_push) begin
                    if (r_count == {1'b0,r_len}) begin
                        r_count <= '0;
                        r_state <= R_IDLE;
                    end
                    else begin
                        r_count     <= r_count + 1'b1;
                        r_curr_addr <= r_next_addr;
                    end
                end
            end

            default: begin
                r_state <= R_IDLE;
            end
        endcase
    end
end

/*
 * Generated one-transfer APB request FIFOs.
 *
 * DW = AW + IW + LW + 3:
 *   PROT + LEN + ADDR + ID
 */
sync_fifo #(
    .AW(2 + LW),
    .DW(AW + IW + LW + 3)
) u_write_address_fifo (
    .clk         (PCLK),
    .rstn        (PRESETn),
    .push        (w_addr_push),
    .pop         (waddr_ren),
    .write_data  (w_calc_addr_ctrl),
    .read_data   (r_write_prot_addr_id),
    .empty       (w_addr_fe),
    .almost_full (w_addr_ff)
);

sync_fifo #(
    .AW(2 + LW),
    .DW(AW + IW + LW + 3)
) u_read_address_fifo (
    .clk         (PCLK),
    .rstn        (PRESETn),
    .push        (r_addr_push),
    .pop         (raddr_ren),
    .write_data  (r_calc_addr_ctrl),
    .read_data   (r_read_prot_addr_id),
    .empty       (r_addr_fe),
    .almost_full (r_addr_ff)
);

endmodule
